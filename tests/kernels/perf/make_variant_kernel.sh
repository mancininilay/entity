#!/usr/bin/env bash
# P2 step 7, M3 (scaling-harness contract 2026-10-30 §1): generates the perf-variant copy of the Bethe-Heitler
# kernel from the production header. The copy is the kernel struct verbatim, templated on the table type, so that
# the two harness table variants (constants; float tables with linear interpolation) can be substituted for the
# production lookup with the same control flow. The production header is not touched; the copy lives in the test
# tree only and compiles only with BH_PERF_VARIANT defined (test build). check_perf_isolation.sh regenerates the
# copy and fails when the committed one differs, so the variant cannot silently diverge from the production kernel.
# Usage: make_variant_kernel.sh <src/kernels/hadronic/bethe_heitler.hpp> <output header>   (Bash 3.2 compatible)
set -e
src="$1"; out="$2"
[ -f "$src" ] || { echo "make_variant_kernel.sh: no source $src"; exit 2; }
start=$(grep -n '^  struct BetheHeitler_kernel {$' "$src" | cut -d: -f1)
[ -n "$start" ] || { echo "make_variant_kernel.sh: kernel struct not found"; exit 2; }
start=$((start - 1))
[ "$(sed -n "${start}p" "$src")" = "  template <class M>" ] || { echo "make_variant_kernel.sh: unexpected template line"; exit 2; }
end=$(awk -v s="$start" 'NR > s && /^  };$/ { print NR; exit }' "$src")
[ -n "$end" ] || { echo "make_variant_kernel.sh: struct end not found"; exit 2; }
{
  cat <<'HDR'
/**
 * @file tests/kernels/perf/bh_perf_kernel_variant.hpp
 * @brief GENERATED by tests/kernels/perf/make_variant_kernel.sh from src/kernels/hadronic/bethe_heitler.hpp:
 *        the Bethe-Heitler kernel struct verbatim, templated on the table type (TablesT in place of
 *        arch::bh::HadronicTables), for the M3 harness variants of the scaling measurement (contract
 *        2026-10-30 §1). PERF BUILD ONLY: compiles only with BH_PERF_VARIANT defined; the variants are
 *        measurement code, never a physics number. Do not edit: regenerate.
 */
#ifndef TESTS_KERNELS_PERF_BH_PERF_KERNEL_VARIANT_HPP
#define TESTS_KERNELS_PERF_BH_PERF_KERNEL_VARIANT_HPP

#ifndef BH_PERF_VARIANT
  #error "bh_perf_kernel_variant.hpp is perf-harness code: compile with BH_PERF_VARIANT (test build only)"
#endif

#include "kernels/hadronic/bethe_heitler.hpp"

namespace kernel::hadronic_perf {
  using namespace ntt;
  using namespace ::kernel::hadronic;

HDR
  sed -n "${start},${end}p" "$src" \
    | sed -e 's/^  template <class M>$/  template <class M, class TablesT>/' \
          -e 's/^  struct BetheHeitler_kernel {$/  struct BetheHeitler_kernel_variant {/' \
          -e 's/const arch::bh::HadronicTables tables;/const TablesT                  tables;/' \
          -e 's/const arch::bh::HadronicTables& tbl/const TablesT\&                 tbl/' \
          -e 's/BetheHeitler_kernel(/BetheHeitler_kernel_variant(/g'
  cat <<'FTR'

} // namespace kernel::hadronic_perf

#endif // TESTS_KERNELS_PERF_BH_PERF_KERNEL_VARIANT_HPP
FTR
} > "$out"
echo "make_variant_kernel.sh: wrote $out from lines $start-$end of $src"
