#!/usr/bin/env python3
"""Tables of the mutation matrix from the logs of run_matrix.sh.

    summarize_matrix.py <this directory>  >  matrix_summary.md
"""
import os
import re
import sys

N = sys.argv[1]
L = os.path.join(N, "logs")
POLICY = ["no_write", "integer_only", "fractional_only", "electrons_only", "positrons_only", "x_only", "y_only"]
GUARD = ["no_dt_guard", "no_mass_guard"]
WHAT = {
    "none": "the policy as committed",
    "no_write": "whole write removed",
    "integer_only": "cell indices only",
    "fractional_only": "offsets only",
    "electrons_only": "electrons only",
    "positrons_only": "positrons only",
    "x_only": "x only",
    "y_only": "y only",
    "no_dt_guard": "finite check of the timestep removed",
    "no_mass_guard": "finite check of the emitter mass removed",
}
arm = re.compile(r"^reused slots, (same cell|neighbouring cells), policy: (\d+) pairs, in-plane currents (\S+) \(electrons\) and "
                 r"(\S+) \(positrons\), continuity residual (\S+) \(limit (\S+)\)")
fresh = re.compile(r"^charge: (\d+) pairs, continuity residuals (\S+) \(leptons not pushed\) and (\S+) \(pushed\)")


def read(m, prec, var, t):
    p = os.path.join(L, "run-%s-%s-%s-t%s.log" % (m, prec, var, t))
    if not os.path.exists(p):
        return None
    lines = open(p).read().splitlines()
    out = {"rc": None, "arms": {}, "failed": [], "first": "", "nfailed": None, "fresh": None}
    for l in lines:
        if l.startswith("rc="):
            out["rc"] = int(l[3:])
        g = arm.match(l)
        if g:
            out["arms"][g.group(1)] = dict(pairs=int(g.group(2)), je=float(g.group(3)), jp=float(g.group(4)),
                                           R=float(g.group(5)), limit=float(g.group(6)))
        g = fresh.match(l)
        if g:
            out["fresh"] = (float(g.group(2)), float(g.group(3)))
        if l.startswith("FAILED CHECK: ") or l.startswith("EXCEPTION: "):
            out["failed"].append(l)
        if l.startswith("failed checks: "):
            out["nfailed"] = int(l.split(": ")[1])
    # the message of the shipped test is the last line before rc that is not a result line
    msgs = [l for l in lines if not l.startswith(("rc=", "charge:", "reused slots,", "rate:", "capacity:", "refusals:"))
            or ("!= 0" in l) or ("(limit" in l and "pairs" not in l)]
    out["first"] = msgs[0] if msgs else ""
    return out


def fmt(x):
    return "0" if x == 0 else "%.3g" % x


print("# Mutation matrix of the charge test (generated by summarize_matrix.py)\n")
print("Source: dev/bh-emission %s. Mac, Apple clang 21, Kokkos 5.0.1 OpenMP.\n" % open(os.path.join(N, "source_head.txt")).read().strip())
print("## 1. Verdict of the shipped test (exit status; 0 = pass)\n")
print("| mutation | single, 1 / 2 / 8 threads | double, 1 / 2 / 8 threads | first failing check (double, 8 threads) |")
print("|---|---|---|---|")
allfail = True
for m in POLICY:
    cells = []
    for prec in ("single", "double"):
        rcs = [read(m, prec, "shipped", t)["rc"] for t in (1, 2, 8)]
        allfail = allfail and all(rc not in (0, None) for rc in rcs)
        cells.append(" / ".join(str(rc) for rc in rcs))
    first = read(m, "double", "shipped", 8)["first"]
    print("| %s | %s | %s | %s |" % (WHAT[m], cells[0], cells[1], first))
for m in GUARD:
    cells = []
    for prec in ("single", "double"):
        r = read(m, prec, "shipped", 8)
        allfail = allfail and r["rc"] not in (0, None)
        cells.append("- / - / %s" % r["rc"])
    print("| %s | %s | %s | %s |" % (WHAT[m], cells[0], cells[1], read(m, "double", "shipped", 8)["first"]))
print("\nEvery mutation fails the shipped test in every run: %s.\n" % ("yes" if allfail else "NO"))

print("## 2. Measurements of the diagnostic copy, policy arms of the reused-slot case\n")
print("J: largest in-plane current of the electrons / of the positrons (the test requires exactly 0). R / limit: continuity "
      "residual over its limit (the test requires < 1). Double precision, 8 threads; the other runs are in section 3.\n")
print("| mutation | same cell: J | same cell: R / limit | neighbouring cells: J | neighbouring cells: R / limit | failed checks |")
print("|---|---|---|---|---|---|")
for m in ["none"] + POLICY:
    r = read(m, "double", "diagnostic", 8)
    a, b = r["arms"]["same cell"], r["arms"]["neighbouring cells"]
    print("| %s | %s / %s | %s | %s / %s | %s | %s |" % (WHAT[m], fmt(a["je"]), fmt(a["jp"]), fmt(a["R"] / a["limit"]),
                                                    fmt(b["je"]), fmt(b["jp"]), fmt(b["R"] / b["limit"]), r["nfailed"]))

print("\n## 3. Smallest margin over the six runs of each mutation (single and double, 1, 2 and 8 threads)\n")
print("For each run the larger of the two arms' R / limit; the table gives the smallest and the largest of these over the six "
      "runs, and which arm detects the mutation (R / limit > 1 or a current that is not zero).\n")
print("| mutation | R / limit, smallest | R / limit, largest | detected by same cell (runs of 6) | detected by neighbouring cells (runs of 6) | failed checks, min to max |")
print("|---|---|---|---|---|---|")
for m in ["none"] + POLICY:
    best, da, db, nf = [], 0, 0, []
    for prec in ("single", "double"):
        for t in (1, 2, 8):
            r = read(m, prec, "diagnostic", t)
            a, b = r["arms"]["same cell"], r["arms"]["neighbouring cells"]
            ra, rb = a["R"] / a["limit"], b["R"] / b["limit"]
            best.append(max(ra, rb))
            da += (ra >= 1 or a["je"] != 0 or a["jp"] != 0)
            db += (rb >= 1 or b["je"] != 0 or b["jp"] != 0)
            nf.append(r["nfailed"])
    print("| %s | %s | %s | %d | %d | %d to %d |" % (WHAT[m], fmt(min(best)), fmt(max(best)), da, db, min(nf), max(nf)))

print("\n## 4. The policy as committed under the diagnostic copy: R / limit of the two arms\n")
print("| precision | threads | pairs | same cell: R, limit, limit / R | neighbouring cells: R, limit, limit / R | fresh slots: not pushed, pushed |")
print("|---|---|---|---|---|---|")
for prec in ("single", "double"):
    for t in (1, 2, 8):
        r = read("none", prec, "diagnostic", t)
        a, b = r["arms"]["same cell"], r["arms"]["neighbouring cells"]
        print("| %s | %s | %d | %.3e, %.3e, %.0f | %.3e, %.3e, %.0f | %.3e, %.3e |" % (
            prec, t, a["pairs"], a["R"], a["limit"], a["limit"] / a["R"], b["R"], b["limit"], b["limit"] / b["R"],
            r["fresh"][0], r["fresh"][1]))

print("\n## 5. Every failed check of the diagnostic copy (double precision, 8 threads)\n")
for m in POLICY:
    r = read(m, "double", "diagnostic", 8)
    print("**%s**\n" % WHAT[m])
    for l in r["failed"]:
        print("- " + l)
    print()
